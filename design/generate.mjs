import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

export const sourceURL = new URL("./turnmark.tokens.json", import.meta.url);
export const outputURL = new URL(
  "../src/generated/design-tokens.css",
  import.meta.url,
);
const kebab = (value) =>
  value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

// Deliberately supports our literal opaque sRGB/dimension subset, not a generic
// DTCG resolver. Fail on new types instead of silently emitting partial tokens.
export function renderTokens(tokens) {
  if (tokens.$extensions?.["app.turnmark"]?.contractVersion !== 1)
    throw new Error("Unsupported Turnmark design contract");
  const entries = (group) =>
    Object.entries(group).filter(([key]) => !key.startsWith("$"));
  for (const key of Object.keys(tokens))
    if (
      !key.startsWith("$") &&
      !["light", "dark", "space", "radius"].includes(key)
    )
      throw new Error(`Unsupported token group: ${key}`);
  const colors = (mode) => {
    const group = tokens[mode];
    if (group?.$type !== "color")
      throw new Error(`Missing color group: ${mode}`);
    return entries(group).map(([name, token]) => {
      const value = token.$value;
      if (
        !/^[a-z][a-zA-Z]+$/.test(name) ||
        (token.$type && token.$type !== "color") ||
        value?.colorSpace !== "srgb" ||
        value.alpha !== 1 ||
        !Array.isArray(value.components) ||
        value.components.length !== 3 ||
        value.components.some(
          (part) => !Number.isFinite(part) || part < 0 || part > 1,
        )
      )
        throw new Error(`Unsupported color: ${mode}.${name}`);
      const hex =
        "#" +
        value.components
          .map((part) =>
            Math.round(part * 255)
              .toString(16)
              .padStart(2, "0"),
          )
          .join("");
      if (value.hex !== hex)
        throw new Error(`Hex/components disagree: ${mode}.${name}`);
      return `  --tm-color-${kebab(name)}: ${hex};`;
    });
  };
  const light = colors("light"),
    dark = colors("dark");
  if (
    entries(tokens.light)
      .map(([key]) => key)
      .sort()
      .join() !==
    entries(tokens.dark)
      .map(([key]) => key)
      .sort()
      .join()
  )
    throw new Error("Light and dark roles must match");
  const dimensions = ["space", "radius"].flatMap((name) => {
    const group = tokens[name];
    if (group?.$type !== "dimension")
      throw new Error(`Missing dimension group: ${name}`);
    return entries(group).map(([key, token]) => {
      if (
        !/^[a-z0-9]+$/.test(key) ||
        (token.$type && token.$type !== "dimension") ||
        token.$value?.unit !== "px" ||
        !Number.isFinite(token.$value.value) ||
        token.$value.value < 0
      )
        throw new Error(`Unsupported dimension: ${name}.${key}`);
      return `  --tm-${name}-${key}: ${token.$value.value}px;`;
    });
  });
  return `/* Generated by node design/generate.mjs. Edit design/turnmark.tokens.json. */\n:root {\n${[...light, ...dimensions].join("\n")}\n}\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {\n${dark.map((line) => "  " + line).join("\n")}\n  }\n}\n:root[data-theme="dark"] {\n${dark.join("\n")}\n}\n`;
}

export function renderSwift(tokens) {
  renderTokens(tokens);
  const entries = (group) =>
    Object.entries(group).filter(([key]) => !key.startsWith("$"));
  const colors = entries(tokens.light).map(
    ([name, token]) =>
      `    static let ${name} = adaptive(0x${token.$value.hex.slice(1)}, 0x${tokens.dark[name].$value.hex.slice(1)})`,
  );
  const dimensions = ["space", "radius"].flatMap((group) =>
    entries(tokens[group]).map(
      ([name, token]) =>
        `    static let ${group}${name[0].toUpperCase() + name.slice(1)}: CGFloat = ${token.$value.value}`,
    ),
  );
  const resultColors = entries(tokens.dark).map(([name, token]) => {
    const rgb = [1, 3, 5].map((start) =>
      parseInt(token.$value.hex.slice(start, start + 2), 16),
    );
    return `    static let ${name} = Color(red: ${rgb[0]} / 255, green: ${rgb[1]} / 255, blue: ${rgb[2]} / 255)`;
  });
  return `// Generated by node design/generate.mjs. Edit design/turnmark.tokens.json.\nimport SwiftUI\n\nenum TurnmarkPalette {\n${[...colors, ...dimensions].join("\n")}\n\n    private static func adaptive(_ light: UInt32, _ dark: UInt32) -> Color {\n        Color(uiColor: UIColor { traits in\n            let hex = traits.userInterfaceStyle == .dark ? dark : light\n            return UIColor(red: CGFloat((hex >> 16) & 255) / 255, green: CGFloat((hex >> 8) & 255) / 255, blue: CGFloat(hex & 255) / 255, alpha: 1)\n        })\n    }\n}\n\n// Signature numerical surface uses the dark palette in both appearances.\nenum TurnmarkResultPalette {\n${resultColors.join("\n")}\n}\n`;
}

export function renderKotlin(tokens) {
  renderTokens(tokens);
  const entries = (group) =>
    Object.entries(group).filter(([key]) => !key.startsWith("$"));
  const properties = entries(tokens.light)
    .map(([name]) => `    val ${name}: Color`)
    .join(",\n");
  const modes = ["light", "dark"].map(
    (mode) =>
      `    val ${mode} = TurnmarkColors(\n${entries(tokens[mode])
        .map(
          ([name, token]) =>
            `        ${name} = Color(0xFF${token.$value.hex.slice(1).toUpperCase()})`,
        )
        .join(",\n")}\n    )`,
  );
  const dimensions = ["space", "radius"].flatMap((group) =>
    entries(tokens[group]).map(
      ([name, token]) =>
        `    val ${group}${name[0].toUpperCase() + name.slice(1)} = ${token.$value.value}.dp`,
    ),
  );
  return `// Generated by node design/generate.mjs. Edit design/turnmark.tokens.json.\npackage net.stanback.turnmark\n\nimport androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.unit.dp\n\ndata class TurnmarkColors(\n${properties}\n)\n\nobject TurnmarkTokens {\n${[...modes, ...dimensions].join("\n")}\n}\n`;
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const tokens = JSON.parse(readFileSync(sourceURL, "utf8"));
  const outputs = [
    [outputURL, renderTokens(tokens)],
    [
      new URL("../apps/ios/Sources/TurnmarkPalette.swift", import.meta.url),
      renderSwift(tokens),
    ],
    [
      new URL(
        "../apps/android/src/main/java/net/stanback/turnmark/TurnmarkTokens.kt",
        import.meta.url,
      ),
      renderKotlin(tokens),
    ],
  ];
  for (const [url, output] of outputs) {
    if (process.argv.includes("--check")) {
      if (readFileSync(url, "utf8") !== output)
        throw new Error(
          `Design tokens are stale: ${fileURLToPath(url)}. Run node design/generate.mjs.`,
        );
    } else writeFileSync(url, output);
  }
  console.log(
    `Design tokens ${process.argv.includes("--check") ? "verified" : "generated"}: ${fileURLToPath(outputURL)}`,
  );
}
